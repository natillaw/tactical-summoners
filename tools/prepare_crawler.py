#!/usr/bin/env python3
"""Installs the Pixel Crawler Free Pack (Anokolisa) into the project: only what the game uses.
  python tools\\prepare_crawler.py "C:\\path\\Pixel_Crawler_-_Free_Pack_2_11.zip"
Safe to re-run. Writes assets/pixel/tilesets/pixel-crawler/*, assets/pixel/enemies/pixel-crawler/<id>/*,
updates assets/ASSET_REGISTRY.json and assets/CREDITS.md. Stdlib only (Python 3.8+)."""
import hashlib, json, os, sys, zipfile
from datetime import date

MOBS = {  # id -> folder inside Entities/Mobs
    "orc": "Orc Crew/Orc", "orc_rogue": "Orc Crew/Orc - Rogue", "orc_shaman": "Orc Crew/Orc - Shaman",
    "orc_warrior": "Orc Crew/Orc - Warrior", "skeleton_base": "Skeleton Crew/Skeleton - Base",
    "skeleton_mage": "Skeleton Crew/Skeleton - Mage", "skeleton_rogue": "Skeleton Crew/Skeleton - Rogue",
    "skeleton_warrior": "Skeleton Crew/Skeleton - Warrior"}
TILES = ["Floors_Tiles.png", "Wall_Tiles.png"]
SOURCE = "https://anokolisa.itch.io/free-pixel-art-asset-pack-topdown-tileset-rpg-16x16-sprites"


def main():
    if len(sys.argv) < 2 or not os.path.isfile(sys.argv[1]):
        sys.exit(__doc__)
    zpath = sys.argv[1]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    sha = hashlib.sha256(open(zpath, "rb").read()).hexdigest().upper()
    z = zipfile.ZipFile(zpath)
    names = {n.replace("\\", "/"): n for n in z.namelist()}

    def find(suffix):
        for k, v in names.items():
            if k.endswith(suffix):
                return v
        sys.exit("missing in zip: " + suffix)

    def put(member, dest):
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "wb") as f:
            f.write(z.read(member))

    tdir = os.path.join(root, "assets", "pixel", "tilesets", "pixel-crawler")
    edir = os.path.join(root, "assets", "pixel", "enemies", "pixel-crawler")
    terms = find("Terms.txt")
    for t in TILES:
        put(find("Environment/Tilesets/" + t), os.path.join(tdir, t))
    n = len(TILES)
    for mid, folder in MOBS.items():
        for anim in ("Idle", "Run", "Death"):
            put(find("Entities/Mobs/%s/%s/%s-Sheet.png" % (folder, anim, anim)), os.path.join(edir, mid, anim.lower() + ".png"))
            n += 1
    put(terms, os.path.join(tdir, "Terms.txt"))
    put(terms, os.path.join(edir, "Terms.txt"))

    reg_path = os.path.join(root, "assets", "ASSET_REGISTRY.json")
    items = []
    if os.path.isfile(reg_path):
        items = json.load(open(reg_path, encoding="utf-8")).get("assets", [])
    today = date.today().isoformat()
    for kind, name, path, cnt in (("tilesets", "Pixel Crawler Free Pack (tiles)", "assets/pixel/tilesets/pixel-crawler", len(TILES)),
                                  ("enemies", "Pixel Crawler Free Pack (mobs)", "assets/pixel/enemies/pixel-crawler", len(MOBS) * 3)):
        sid = name.lower().replace("(", "").replace(")", "").replace(" ", "-")
        old = next((a for a in items if a.get("id") == sid), None)
        entry = {"id": sid, "name": name, "kind": kind, "source": SOURCE, "author": "Anokolisa",
                 "license": "Author Terms (free pack)", "license_url": "", "frame_size": 16, "modified": "no",
                 "notes": "Credit optional. Commercial use OK. Do not resell the assets or sell them as a final product. Only a selection is installed. Terms.txt kept next to the files.",
                 "status": old["status"] if old else "Imported", "sha256": sha, "original_file": os.path.basename(zpath),
                 "path": path, "files": cnt, "license_file_in_pack": True,
                 "imported": old["imported"] if old else today, "updated": today}
        items = [a for a in items if a.get("id") != sid] + [entry]
    if os.path.isfile(reg_path):
        open(reg_path + ".bak", "wb").write(open(reg_path, "rb").read())
    os.makedirs(os.path.dirname(reg_path), exist_ok=True)
    json.dump({"assets": items}, open(reg_path, "w", encoding="utf-8"), indent=2)
    md = ["# Credits", "", "Generated by tools\\Import-Asset.ps1 / tools\\prepare_crawler.py from assets\\ASSET_REGISTRY.json. Do not edit by hand.", ""]
    for a in sorted(items, key=lambda a: a["name"]):
        lic = "[%s](%s)" % (a["license"], a["license_url"]) if a.get("license_url") else a["license"]
        md.append("- **%s** by %s - %s - %s (%s)" % (a["name"], a["author"], lic, a["source"], a["status"]))
    open(os.path.join(root, "assets", "CREDITS.md"), "w", encoding="utf-8").write("\r\n".join(md) + "\r\n")
    print("Installed %d files. Next: open Godot once (import), then tools\\Run-Tests.ps1 (expect 9 suites PASS)." % n)


main()
