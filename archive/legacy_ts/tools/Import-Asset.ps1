<#
 T-022: registers an asset pack/file in assets\ASSET_REGISTRY.json and regenerates assets\CREDITS.md.
 Example:
   .\tools\Import-Asset.ps1 -File "$HOME\Downloads\tiny-pixel-fantasy1.zip" -Name "Tiny Pixel Fantasy Base Pack" `
      -Kind tilesets -Source "https://cazwolf.itch.io/tiny-pixel-fantasy1" -Author "Caz" `
      -License "CC BY 4.0" -LicenseUrl "https://creativecommons.org/licenses/by/4.0/" -FrameSize 16
 Kinds: characters enemies tilesets ui effects audio fonts
 -File may be a full path or just a file name sitting in assets\_inbox.
 Re-running with the same file updates its entry (keyed by SHA-256): no duplicates.
 -Approve marks it Approved (default status: Imported). -List shows registry + unregistered inbox files.
#>
param(
  [string]$File = "", [string]$Name = "",
  [ValidateSet("", "characters", "enemies", "tilesets", "ui", "effects", "audio", "fonts")][string]$Kind = "",
  [string]$Source = "", [string]$Author = "", [string]$License = "", [string]$LicenseUrl = "",
  [int]$FrameSize = 0, [string]$Modified = "no", [string]$Notes = "",
  [switch]$Approve, [switch]$List
)
$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
$assets = Join-Path $root "assets"
$inbox = Join-Path $assets "_inbox"
$done = Join-Path $inbox "_done"
$regPath = Join-Path $assets "ASSET_REGISTRY.json"
$credPath = Join-Path $assets "CREDITS.md"
$utf8 = New-Object System.Text.UTF8Encoding $false

foreach ($d in @($assets, $inbox, $done)) { if (-not (Test-Path $d)) { New-Item -ItemType Directory -Force -Path $d | Out-Null } }
$gd = Join-Path $inbox ".gdignore"
if (-not (Test-Path $gd)) { New-Item -ItemType File -Path $gd | Out-Null }   # Godot must not import raw zips

$list = @()
if (Test-Path $regPath) {
  $raw = Get-Content $regPath -Raw
  if ($raw.Trim()) { $list = @((ConvertFrom-Json $raw).assets) }
}

function Save-Registry($items) {
  if (Test-Path $regPath) { Copy-Item $regPath ($regPath + ".bak") -Force }
  $json = ConvertTo-Json -InputObject @{ assets = @($items) } -Depth 6
  [IO.File]::WriteAllText($regPath, $json, $utf8)
  $md = @("# Credits", "", "Generated by tools\Import-Asset.ps1 from assets\ASSET_REGISTRY.json. Do not edit by hand.", "")
  foreach ($a in ($items | Sort-Object name)) {
    $lic = $a.license
    if ($a.license_url) { $lic = "[" + $a.license + "](" + $a.license_url + ")" }
    $md += "- **" + $a.name + "** by " + $a.author + " - " + $lic + " - " + $a.source + " (" + $a.status + ")"
  }
  [IO.File]::WriteAllText($credPath, ($md -join "`r`n") + "`r`n", $utf8)
}

if ($List) {
  Write-Host "Registered:"
  if ($list.Count -eq 0) { Write-Host "  (none)" }
  $list | ForEach-Object { Write-Host ("  {0,-32} {1,-10} {2,-12} {3}" -f $_.name, $_.kind, $_.license, $_.status) }
  $known = @($list | ForEach-Object { $_.sha256 })
  $pending = Get-ChildItem $inbox -File -ErrorAction SilentlyContinue | Where-Object { $_.Name -ne ".gdignore" -and ($known -notcontains (Get-FileHash $_.FullName -Algorithm SHA256).Hash) }
  Write-Host "`nIn inbox, not registered:"
  if (-not $pending) { Write-Host "  (none)" }
  $pending | ForEach-Object { Write-Host ("  " + $_.Name) }
  exit 0
}

$missing = @()
if (-not $File) { $missing += "-File" }
if (-not $Name) { $missing += "-Name" }
if (-not $Kind) { $missing += "-Kind" }
if (-not $Source) { $missing += "-Source" }
if (-not $Author) { $missing += "-Author" }
if (-not $License) { $missing += "-License" }
if ($missing.Count -gt 0) { Write-Host ("Missing: " + ($missing -join ", ") + "  (see the header of this script for an example)") -ForegroundColor Red; exit 1 }

$src = $File
if (-not (Test-Path $src)) { $src = Join-Path $inbox $File }
if (-not (Test-Path $src)) { Write-Host "File not found: $File (also looked in assets\_inbox)" -ForegroundColor Red; exit 1 }
$src = (Resolve-Path $src).Path
$sha = (Get-FileHash $src -Algorithm SHA256).Hash
$slug = ($Name.ToLower() -replace "[^a-z0-9]+", "-").Trim("-")
$destRel = "assets/pixel/$Kind/$slug"
$dest = Join-Path $root ($destRel -replace "/", "\")
New-Item -ItemType Directory -Force -Path $dest | Out-Null

if ([IO.Path]::GetExtension($src).ToLower() -eq ".zip") { Expand-Archive -Path $src -DestinationPath $dest -Force }
else { Copy-Item $src $dest -Force }
$count = @(Get-ChildItem $dest -Recurse -File).Count
$hasLicenseFile = @(Get-ChildItem $dest -Recurse -File | Where-Object { $_.Name -match "licen[sc]e|eula|terms|readme" }).Count -gt 0

$old = $list | Where-Object { $_.sha256 -eq $sha } | Select-Object -First 1
$status = "Imported"
if ($Approve) { $status = "Approved" } elseif ($old -and $old.status -eq "Approved") { $status = "Approved" }
$firstDate = (Get-Date -Format "yyyy-MM-dd")
if ($old) { $firstDate = $old.imported }

$entry = [ordered]@{
  id = $slug; name = $Name; kind = $Kind; source = $Source; author = $Author
  license = $License; license_url = $LicenseUrl; frame_size = $FrameSize
  modified = $Modified; notes = $Notes; status = $status
  sha256 = $sha; original_file = [IO.Path]::GetFileName($src)
  path = $destRel; files = $count; license_file_in_pack = $hasLicenseFile
  imported = $firstDate; updated = (Get-Date -Format "yyyy-MM-dd")
}
$list = @($list | Where-Object { $_.sha256 -ne $sha }) + @([pscustomobject]$entry)
Save-Registry $list

if ((Split-Path $src -Parent) -eq (Resolve-Path $inbox).Path) { Move-Item $src (Join-Path $done ([IO.Path]::GetFileName($src))) -Force }

Write-Host "Imported '$Name' -> $destRel  ($count files, status $status)" -ForegroundColor Green
if (-not $hasLicenseFile) { Write-Host "No license/EULA/readme file found inside the pack: save the license text next to it." -ForegroundColor Yellow }
if ($License -match "BY") { Write-Host "Attribution required: assets\CREDITS.md was regenerated; ship it with the game." -ForegroundColor Yellow }
Write-Host "Next: open Godot once so it imports the new files, then run tools\Run-Tests.ps1"
